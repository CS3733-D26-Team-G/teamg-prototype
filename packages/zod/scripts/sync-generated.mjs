import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, '..');
const generatedRoot = path.join(packageRoot, 'generated', 'schemas');
const enumsDir = path.join(generatedRoot, 'enums');

const prismaImportPattern = /from\s+['"](?:\.\.\/)+(?:db\/generated\/prisma\/client\.ts)['"]/g;

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) return walk(fullPath);
      return [fullPath];
    }),
  );
  return files.flat();
}

async function rewritePrismaTypeImports() {
  const files = (await walk(generatedRoot)).filter((file) => file.endsWith('.ts'));

  await Promise.all(
    files.map(async (file) => {
      const original = await fs.readFile(file, 'utf8');
      const rewritten = original.replace(prismaImportPattern, "from '@repo/db/client'");

      if (rewritten !== original) {
        await fs.writeFile(file, rewritten, 'utf8');
      }
    }),
  );
}

async function ensureEnumsIndex() {
  const enumFiles = (await fs.readdir(enumsDir))
    .filter((file) => file.endsWith('.schema.ts') && file !== 'index.ts')
    .sort();

  const contents = [
    '/**',
    ' * Enum Schemas Index',
    ' * Auto-generated by packages/zod/scripts/sync-generated.mjs',
    ' */',
    '',
    ...enumFiles.map((file) => `export * from './${file}';`),
    '',
  ].join('\n');

  await fs.writeFile(path.join(enumsDir, 'index.ts'), contents, 'utf8');
}

await rewritePrismaTypeImports();
await ensureEnumsIndex();
